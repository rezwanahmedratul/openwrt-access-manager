import crypto from 'crypto';
import { SignJWT, jwtVerify } from 'jose';
import { SessionUser } from './types';

export const AUTH_COOKIE_NAME = 'openwrt_session';

/**
 * In-memory set for revoked tokens / JTIs.
 */
const revokedTokens = new Set<string>();

/**
 * Constant-time comparison between two strings using SHA-256 digests.
 * Prevents timing attacks and length leakage.
 */
export function timingSafeCompare(a?: string | null, b?: string | null): boolean {
  if (typeof a !== 'string' || typeof b !== 'string') {
    return false;
  }
  const hashA = crypto.createHash('sha256').update(a).digest();
  const hashB = crypto.createHash('sha256').update(b).digest();
  return crypto.timingSafeEqual(hashA, hashB);
}

/**
 * Returns the session secret. Fails closed if missing.
 */
function getSessionSecret(): string | null {
  const secret = process.env.SESSION_SECRET;
  if (!secret || secret.trim() === '') {
    return null;
  }
  return secret;
}

/**
 * Returns cookie options for the session cookie.
 */
export function getSessionCookieOptions(maxAgeSeconds = 7 * 24 * 60 * 60) {
  return {
    httpOnly: true,
    secure: process.env.NODE_ENV === 'production',
    sameSite: 'lax' as const,
    path: '/',
    maxAge: maxAgeSeconds,
  };
}

/**
 * Invalidate / revoke a session token or JTI server-side.
 */
export async function revokeSession(tokenOrJti: string): Promise<void> {
  if (!tokenOrJti || typeof tokenOrJti !== 'string') return;
  revokedTokens.add(tokenOrJti);

  // If token is a JWT, also extract and revoke the JTI and payload
  if (tokenOrJti.includes('.')) {
    try {
      const parts = tokenOrJti.split('.');
      if (parts[1]) {
        const payload = JSON.parse(Buffer.from(parts[1], 'base64url').toString('utf8'));
        if (payload?.jti) {
          revokedTokens.add(payload.jti);
        }
      }
    } catch {}
  }

  // Attempt to write to Redis/cache if available
  try {
    const { cacheSet } = await import('./cache');
    await cacheSet(`revoked:${tokenOrJti}`, true, 7 * 24 * 60 * 60);
  } catch {}
}

/**
 * Check if a session token or JTI has been revoked.
 */
export function isSessionRevoked(tokenOrJti: string): boolean {
  if (!tokenOrJti) return false;
  if (revokedTokens.has(tokenOrJti)) return true;

  if (tokenOrJti.includes('.')) {
    try {
      const parts = tokenOrJti.split('.');
      if (parts[1]) {
        const payload = JSON.parse(Buffer.from(parts[1], 'base64url').toString('utf8'));
        if (payload?.jti && revokedTokens.has(payload.jti)) {
          return true;
        }
      }
    } catch {}
  }
  return false;
}

/**
 * Clear the revocation list (useful for testing).
 */
export function clearRevokedSessions(): void {
  revokedTokens.clear();
}

/**
 * Synchronous session token verification using HMAC-SHA256 and constant-time comparison.
 * Fully compatible with tokens generated by `jose.SignJWT` with alg: 'HS256'.
 * Returns null if token is invalid, expired, tampered, revoked, or if SESSION_SECRET is missing.
 */
export function parseSessionToken(token: string | undefined | null): SessionUser | null {
  if (!token || typeof token !== 'string') return null;

  const secret = getSessionSecret();
  if (!secret) {
    // Fail closed: without SESSION_SECRET, no token can be validated
    return null;
  }

  if (isSessionRevoked(token)) {
    return null;
  }

  try {
    const parts = token.split('.');
    if (parts.length !== 3) {
      return null;
    }

    const [headerB64, payloadB64, signature] = parts;
    if (!headerB64 || !payloadB64 || !signature) {
      return null;
    }

    // Verify HMAC-SHA256 signature in constant time
    const expectedSig = crypto
      .createHmac('sha256', secret)
      .update(`${headerB64}.${payloadB64}`)
      .digest('base64url');

    const sigBuf = Buffer.from(signature);
    const expectedBuf = Buffer.from(expectedSig);

    if (sigBuf.length !== expectedBuf.length || !crypto.timingSafeEqual(sigBuf, expectedBuf)) {
      return null;
    }

    const payload = JSON.parse(Buffer.from(payloadB64, 'base64url').toString('utf-8'));
    if (!payload || !payload.id || !payload.username) {
      return null;
    }

    if (payload.role !== 'admin' && payload.role !== 'subadmin') {
      return null;
    }

    // Check expiration (exp is in seconds for standard JWT, or ms for legacy)
    if (payload.exp && typeof payload.exp === 'number') {
      const expMs = payload.exp > 100000000000 ? payload.exp : payload.exp * 1000;
      if (Date.now() > expMs) {
        return null;
      }
    }

    // Check JTI revocation
    if (payload.jti && isSessionRevoked(payload.jti)) {
      return null;
    }

    return {
      id: payload.id,
      username: payload.username,
      role: payload.role,
    };
  } catch {
    return null;
  }
}

/**
 * Asynchronous token verification using `jose.jwtVerify`.
 */
export async function verifySessionToken(token: string | undefined | null): Promise<SessionUser | null> {
  if (!token || typeof token !== 'string') return null;

  const secret = getSessionSecret();
  if (!secret) {
    return null;
  }

  if (isSessionRevoked(token)) {
    return null;
  }

  try {
    const secretKey = new TextEncoder().encode(secret);
    const { payload } = await jwtVerify(token, secretKey, {
      algorithms: ['HS256'],
    });

    if (!payload || !payload.id || !payload.username) {
      return null;
    }

    const role = payload.role as string;
    if (role !== 'admin' && role !== 'subadmin') {
      return null;
    }

    if (payload.jti && isSessionRevoked(payload.jti)) {
      return null;
    }

    return {
      id: payload.id as string,
      username: payload.username as string,
      role,
    };
  } catch {
    return null;
  }
}

/**
 * Creates a cryptographically signed session token using `jose.SignJWT`.
 * Valid for 7 days by default. Fails closed if SESSION_SECRET is missing.
 */
export async function createSessionToken(
  user: SessionUser,
  options?: { expiresIn?: string }
): Promise<string> {
  const secret = getSessionSecret();
  if (!secret) {
    throw new Error('SESSION_SECRET environment variable is missing');
  }

  const secretKey = new TextEncoder().encode(secret);
  const jti = crypto.randomUUID();

  return await new SignJWT({
    id: user.id,
    username: user.username,
    role: user.role,
  })
    .setProtectedHeader({ alg: 'HS256', typ: 'JWT' })
    .setJti(jti)
    .setIssuedAt()
    .setExpirationTime(options?.expiresIn || '7d')
    .sign(secretKey);
}

/**
 * Synchronous helper to create an HS256 signed session token using Node crypto.
 */
export function createSessionTokenSync(
  user: SessionUser,
  expiresInSeconds = 7 * 24 * 60 * 60
): string {
  const secret = getSessionSecret();
  if (!secret) {
    throw new Error('SESSION_SECRET environment variable is missing');
  }

  const nowSec = Math.floor(Date.now() / 1000);
  const jti = crypto.randomUUID();

  const header = { alg: 'HS256', typ: 'JWT' };
  const payload = {
    id: user.id,
    username: user.username,
    role: user.role,
    jti,
    iat: nowSec,
    exp: nowSec + expiresInSeconds,
  };

  const headerB64 = Buffer.from(JSON.stringify(header)).toString('base64url');
  const payloadB64 = Buffer.from(JSON.stringify(payload)).toString('base64url');
  const signature = crypto
    .createHmac('sha256', secret)
    .update(`${headerB64}.${payloadB64}`)
    .digest('base64url');

  return `${headerB64}.${payloadB64}.${signature}`;
}

/**
 * Synchronously extracts and validates session user from a Request.
 */
export function getSessionFromRequest(request?: Request): SessionUser | null {
  if (request) {
    // 1. Check Authorization: Bearer <token>
    const authHeader = request.headers.get('authorization') || '';
    if (authHeader.startsWith('Bearer ')) {
      const bearerToken = authHeader.slice(7).trim();
      if (bearerToken) {
        const userFromBearer = parseSessionToken(bearerToken);
        if (userFromBearer) {
          return userFromBearer;
        }
      }
    }

    // 2. Check Cookie header
    const cookieHeader = request.headers.get('cookie') || '';
    const match = cookieHeader.match(new RegExp(`(?:^|;\\s*)${AUTH_COOKIE_NAME}=([^;]+)`));
    if (match && match[1]) {
      const userFromCookie = parseSessionToken(decodeURIComponent(match[1]));
      if (userFromCookie) {
        return userFromCookie;
      }
    }
  }

  return null;
}

/**
 * Asynchronously retrieves the current session user.
 */
export async function getSession(request?: Request): Promise<SessionUser | null> {
  const syncSession = getSessionFromRequest(request);
  if (syncSession) return syncSession;

  try {
    const { cookies } = await import('next/headers');
    const cookieStore = await cookies();
    const sessionCookie = cookieStore.get(AUTH_COOKIE_NAME)?.value;
    return parseSessionToken(sessionCookie);
  } catch {
    return null;
  }
}

/**
 * Custom error for unauthorized/forbidden access.
 */
export class AuthError extends Error {
  status: number;
  constructor(message: string, status = 401) {
    super(message);
    this.name = 'AuthError';
    this.status = status;
  }
}

/**
 * Centralized authorization helper: requires an authenticated session.
 * Throws AuthError (status 401) if not authenticated.
 */
export async function requireAuth(request?: Request): Promise<SessionUser> {
  const user = await getSession(request);
  if (!user) {
    throw new AuthError('Unauthorized: Authentication required', 401);
  }
  return user;
}

/**
 * Centralized authorization helper: requires an admin session.
 * Throws AuthError (status 401 if unauthenticated, 403 if not admin).
 */
export async function requireAdmin(request?: Request): Promise<SessionUser> {
  const user = await requireAuth(request);
  if (user.role !== 'admin') {
    throw new AuthError('Forbidden: Administrator access required', 403);
  }
  return user;
}

/**
 * Centralized router authentication helper.
 * Constant-time comparison, fails closed if ROUTER_SECRET is missing, no default secrets in production, no bypasses.
 */
export async function authenticateRouter(requestOrToken: Request | string): Promise<boolean> {
  let token = '';

  if (typeof requestOrToken === 'string') {
    token = requestOrToken.trim();
    if (token.startsWith('Bearer ')) {
      token = token.slice(7).trim();
    }
  } else if (requestOrToken && typeof requestOrToken === 'object' && 'headers' in requestOrToken) {
    const request = requestOrToken as Request;
    // Allow authenticated admin/subadmin sessions to preview/download router configs
    const session = getSessionFromRequest(request);
    if (session) {
      return true;
    }

    const authHeader = request.headers.get('authorization') || '';
    if (authHeader.startsWith('Bearer ')) {
      token = authHeader.slice(7).trim();
    } else {
      token = request.headers.get('x-router-token')?.trim() || '';
    }
  }

  if (!token) {
    return false;
  }

  // Check ROUTER_SECRET environment variable
  const envSecret = process.env.ROUTER_SECRET?.trim();
  const isProduction = process.env.NODE_ENV === 'production';

  // In production, reject default / insecure secrets
  const isInsecureDefault =
    envSecret === 'openwrt-secret-token-change-in-production' ||
    envSecret === 'your-secure-secret-here';

  if (envSecret && !(isProduction && isInsecureDefault)) {
    if (timingSafeCompare(token, envSecret)) {
      return true;
    }
  }

  // Check database for active router token (supports token rotation)
  try {
    const isSupabaseConfigured = Boolean(
      process.env.NEXT_PUBLIC_SUPABASE_URL && process.env.NEXT_PUBLIC_SUPABASE_URL.startsWith('http')
    );
    if (isSupabaseConfigured) {
      const { getServiceSupabase } = await import('./supabase');
      const supabase = getServiceSupabase();
      const { data } = await supabase
        .from('app_settings')
        .select('value')
        .eq('key', 'router_token')
        .maybeSingle();

      if (data && data.value) {
        const storedVal = typeof data.value === 'string' ? data.value : JSON.stringify(data.value);
        let targetToken = storedVal;
        try {
          const parsed = JSON.parse(storedVal);
          if (parsed && typeof parsed === 'object') {
            if (parsed.token) targetToken = parsed.token;
            else if (parsed.token_hash) targetToken = parsed.token_hash;
          }
        } catch {}

        if (targetToken.startsWith('scrypt:') || targetToken.startsWith('pbkdf2:')) {
          const { verifyPasswordSync } = await import('./password');
          const verifyRes = verifyPasswordSync(token, targetToken);
          if (verifyRes.valid) return true;
        } else if (timingSafeCompare(token, targetToken)) {
          return true;
        }
      }
    } else {
      const { getMockState } = await import('./mock-store');
      const state = getMockState();
      if (state.mockRouterToken && !state.mockRouterToken.revoked && state.mockRouterToken.token_hash) {
        const targetToken = state.mockRouterToken.token_hash;
        if (targetToken.startsWith('scrypt:') || targetToken.startsWith('pbkdf2:')) {
          const { verifyPasswordSync } = await import('./password');
          const verifyRes = verifyPasswordSync(token, targetToken);
          if (verifyRes.valid) return true;
        } else if (timingSafeCompare(token, targetToken)) {
          return true;
        }
      }
    }
  } catch (err) {
    console.error('Error verifying router token from database:', err);
  }

  // Fail closed if ROUTER_SECRET is missing or does not match
  return false;
}

/**
 * CSRF protection helper for mutating HTTP methods (POST, PUT, PATCH, DELETE).
 * Verifies Origin/Referer matches the request host.
 */
export function verifyCsrf(request: Request): boolean {
  const method = request.method?.toUpperCase();
  if (!method || ['GET', 'HEAD', 'OPTIONS'].includes(method)) {
    return true;
  }

  // Exempt non-browser or bearer-authenticated requests (e.g. mobile app, router sync)
  const authHeader = request.headers.get('authorization') || '';
  if (authHeader.startsWith('Bearer ')) {
    return true;
  }

  const origin = request.headers.get('origin');
  const referer = request.headers.get('referer');
  const host = request.headers.get('x-forwarded-host') || request.headers.get('host');

  if (!origin && !referer) {
    // If neither origin nor referer is provided, check for custom header
    const customHeader = request.headers.get('x-csrf-token') || request.headers.get('x-requested-with');
    return Boolean(customHeader);
  }

  try {
    const originUrl = origin ? new URL(origin) : new URL(referer!);
    if (!host) return true;
    const hostName = host.split(':')[0].toLowerCase();
    const originHostName = originUrl.hostname.toLowerCase();

    // Allow localhost in development
    const isDev = process.env.NODE_ENV !== 'production';
    if (isDev && (originHostName === 'localhost' || originHostName === '127.0.0.1')) {
      return true;
    }

    return originHostName === hostName;
  } catch {
    return false;
  }
}
