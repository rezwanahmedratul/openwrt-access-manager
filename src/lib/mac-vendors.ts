/**
 * Extract manufacturer brand name from a MAC address string.
 * Supports various formats (XX:XX:XX:XX:XX:XX, XX-XX-XX-XX-XX-XX, or raw hex).
 */
export function getMacVendor(mac: string | undefined | null): string | null {
  if (!mac || typeof mac !== 'string') return null;

  // Clean hex characters
  const clean = mac.replace(/[^a-fA-F0-9]/g, '').toUpperCase();
  if (clean.length < 6) return null;

  // Check 6-hex OUI (first 3 bytes: XX:XX:XX)
  const oui = `${clean.slice(0, 2)}:${clean.slice(2, 4)}:${clean.slice(4, 6)}`;
  return VENDOR_PREFIXES[oui] || null;
}

/**
 * Format a MAC address as the user types:
 * - Strips non-hex characters
 * - Uppercases
 * - Inserts ':' every 2 characters
 * - Max 17 characters (XX:XX:XX:XX:XX:XX)
 */
export function formatMacInput(input: string): string {
  if (!input) return '';
  const clean = input.replace(/[^0-9a-fA-F]/g, '').toUpperCase().slice(0, 12);
  const parts: string[] = [];
  for (let i = 0; i < clean.length; i += 2) {
    parts.push(clean.slice(i, i + 2));
  }
  return parts.join(':');
}
